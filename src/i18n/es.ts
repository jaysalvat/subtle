/** A file name as shown in messages: long ones cut in the middle, start and ".es.srt" kept. */
const f = (name: string) => middleEllipsis(name, 40);
/** "12 nov, 14:05" (today: "hoy, 14:05"). */
const when = (d: Date) => {
  const time = d.toLocaleTimeString('es-ES', { hour: '2-digit', minute: '2-digit' });
  return d.toDateString() === new Date().toDateString() ? `hoy, ${time}` : `${d.toLocaleDateString('es-ES', { day: 'numeric', month: 'short' })}, ${time}`;
};
/** Spanish plural: only 1 is singular ("0 subtítulos"). */
const s = (n: number) => (n === 1 ? '' : 's');
const subs = (n: number) => `${n} subtítulo${s(n)}`;
/** What a tool will do, before Apply, from a regular infinitive: "Se modificarán 3 subtítulos.", "Ningún subtítulo se modificará." */
const will = (n: number, verb: string) => (n ? `Se ${verb}${n === 1 ? 'á' : 'án'} ${subs(n)}.` : `Ningún subtítulo se ${verb}á.`);
/** A language name inside a sentence: "al inglés" (the names may start with a capital in lists). */
const low = (name: string) => name.charAt(0).toLocaleLowerCase('es') + name.slice(1);
/** Decimal comma. */
const dec = (x: number | string) => String(x).replace('.', ',');

