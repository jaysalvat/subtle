/** A file name as shown in messages: long ones cut in the middle, start and ".fr.srt" kept. */
const f = (name: string) => middleEllipsis(name, 40);
/** What a tool will do, before Apply: "3 subtitles will be changed.", "No subtitle will be changed." */
/** "1 subtitle", "12 subtitles": every tool's button says how many it acts on ("Clean 12 subtitles"). */
const subs = (n: number) => `${n} ${n === 1 ? 'subtitle' : 'subtitles'}`;
const will = (n: number, done: string) => (n ? `${n} ${n === 1 ? 'subtitle' : 'subtitles'} will be ${done}.` : `No subtitle will be ${done}.`);
/** "12 Nov, 14:05" (today: "today, 14:05"). */
const when = (d: Date) => {
  const time = d.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' });
  return d.toDateString() === new Date().toDateString() ? `today, ${time}` : `${d.toLocaleDateString('en-GB', { day: 'numeric', month: 'short' })}, ${time}`;
};

