/** A file name as shown in messages: long ones cut in the middle, start and ".fr.srt" kept. */
const f = (name: string) => middleEllipsis(name, 40);
/** "12 nov., 14:05" (today: "aujourd’hui, 14:05"). */
const when = (d: Date) => {
  const time = d.toLocaleTimeString('fr-FR', { hour: '2-digit', minute: '2-digit' });
  return d.toDateString() === new Date().toDateString()
    ? `aujourd’hui, ${time}`
    : `${d.toLocaleDateString('fr-FR', { day: 'numeric', month: 'short' })}, ${time}`;
};
/** French plural: 0 and 1 are singular. */
const s = (n: number) => (n <= 1 ? '' : 's');
const subs = (n: number) => `${n} sous-titre${s(n)}`;
/** What a tool will do, before Apply: « 3 sous-titres seront modifiés. », « Aucun sous-titre ne sera modifié. » */
const will = (n: number, done: string) => (n ? `${subs(n)} ${n > 1 ? 'seront' : 'sera'} ${done}${s(n)}.` : `Aucun sous-titre ne sera ${done}.`);
/** A language name inside a sentence: « en anglais » (the names start with a capital in lists). */
const low = (name: string) => name.charAt(0).toLocaleLowerCase('fr') + name.slice(1);
/** Decimal comma. */
const dec = (x: number | string) => String(x).replace('.', ',');

